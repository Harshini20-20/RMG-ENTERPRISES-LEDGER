
import os
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


def _require_database_url():
    url = os.environ.get("DATABASE_URL")

    if not url:
        raise RuntimeError(
            "DATABASE_URL is not configured. "
            "Set it in your environment before starting the app."
        )

    return url



class DatabaseConnection:
    """Small compatibility layer for existing parameterized SQL."""

    def __init__(self, connection):
        self._connection = connection

    def execute(self, query, params=None):
        # Convert the existing SQLite placeholders to PostgreSQL placeholders.
        query = query.replace("?", "%s")
        return self._connection.execute(query, params or ())


@contextmanager
def db_conn():
    database_url = _require_database_url()

    with psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=15,
        autocommit=False,
    ) as connection:
        yield DatabaseConnection(connection)


def init_db():
    statements = [
        """
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL CHECK (role IN ('admin', 'agent')),
            active INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS retailers (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            address TEXT DEFAULT '',
            phone TEXT DEFAULT '',
            agent_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
            active INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS bills (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            retailer_id BIGINT NOT NULL REFERENCES retailers(id),
            bill_number TEXT NOT NULL,
            due_paise BIGINT NOT NULL CHECK (due_paise > 0),
            created_by BIGINT NOT NULL REFERENCES users(id),
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE (retailer_id, bill_number)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS payments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            retailer_id BIGINT NOT NULL REFERENCES retailers(id),
            amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
            note TEXT DEFAULT '',
            created_by BIGINT NOT NULL REFERENCES users(id),
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            payment_mode TEXT NOT NULL DEFAULT 'LEGACY',
            proof_filename TEXT,
            handover_status TEXT NOT NULL DEFAULT 'legacy',
            handover_confirmed_by BIGINT REFERENCES users(id),
            handover_confirmed_at TIMESTAMPTZ
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS audit_log (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            actor_id BIGINT NOT NULL REFERENCES users(id),
            action TEXT NOT NULL,
            details TEXT DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        ALTER TABLE payments
        ADD COLUMN IF NOT EXISTS payment_mode TEXT NOT NULL DEFAULT 'LEGACY'
        """,
        """
        ALTER TABLE payments
        ADD COLUMN IF NOT EXISTS proof_filename TEXT
        """,
        """
        ALTER TABLE payments
        ADD COLUMN IF NOT EXISTS handover_status TEXT NOT NULL DEFAULT 'legacy'
        """,
        """
        ALTER TABLE payments
        ADD COLUMN IF NOT EXISTS handover_confirmed_by BIGINT
        REFERENCES users(id)
        """,
        """
        ALTER TABLE payments
        ADD COLUMN IF NOT EXISTS handover_confirmed_at TIMESTAMPTZ
        """,
    ]

    with db_conn() as connection:
        for statement in statements:
            connection.execute(statement)
